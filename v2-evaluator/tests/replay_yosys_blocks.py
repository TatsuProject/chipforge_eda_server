"""Replay cached block synth scripts inside either image (one block at a time).

Inputs are a directory of cache-key/{input.json,abc.constr,synth.ys}; fixtures
contains latch_map.v and abc_map.abc. Only paths and unused JSON output change.
Keep raw netlists for an independent byte comparison; ignore only line 1 when
comparing versions. Any synthesis failure aborts rather than counting as equal.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess
import time


def digest(path):
    hashes = {name: hashlib.new(name) for name in ('sha256', 'md5')}
    with path.open('rb') as f:
        header = f.readline()
        if not header.startswith(b'/* Generated by Yosys '):
            raise ValueError(f'Unexpected generated header: {header!r}')
        for data in iter(lambda: f.read(1024 * 1024), b''):
            for h in hashes.values():
                h.update(data)
    return {name: h.hexdigest() for name, h in hashes.items()}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--inputs', type=Path, required=True)
    parser.add_argument('--fixtures', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    args.output.mkdir(parents=True, exist_ok=True)
    results = []
    for source in sorted(args.inputs.iterdir()):
        if not (source / 'synth.ys').is_file():
            continue
        work = args.output / source.name
        work.mkdir(exist_ok=True)
        script = (source / 'synth.ys').read_text()
        script = re.sub(r'^read_json "[^"]*"', f'read_json "{source}/input.json"', script, flags=re.M)
        script = re.sub(r'-constr "[^"]*"', f'-constr "{source}/abc.constr"', script)
        lib = '/opt/cf/pdk/nangate45/lib/NangateOpenCellLibrary_typical.lib'
        script = re.sub(r'"[^"]*/NangateOpenCellLibrary_typical.lib"', f'"{lib}"', script)
        for filename in ('latch_map.v', 'abc_map.abc'):
            script = re.sub(r'"[^"]*/' + re.escape(filename) + '"', f'"{args.fixtures}/{filename}"', script)
        script = re.sub(r'^write_json.*\n', '', script, flags=re.M)
        script = re.sub(r'^tee -o "[^"]*"', f'tee -o "{work}/stat.json"', script, flags=re.M)
        mapped = work / 'mapped.v'
        script = re.sub(r'^write_verilog -noattr "[^"]*"', f'write_verilog -noattr "{mapped}"', script, flags=re.M)
        ys = work / 'synth.ys'
        ys.write_text(script)
        start = time.monotonic()
        with (work / 'synth.log').open('w') as log:
            result = subprocess.run(['/usr/bin/time', '-v', 'nice', '-n', '10', 'yosys', '-s', str(ys)],
                                    stdout=log, stderr=subprocess.STDOUT)
        record = {'key': source.name, 'rc': result.returncode, 'wall_s': round(time.monotonic() - start, 3)}
        if result.returncode == 0:
            record.update(digest(mapped))
        results.append(record)
        (args.output / 'results.json').write_text(json.dumps(results, indent=2) + '\n')
        print(json.dumps(record), flush=True)
        if result.returncode:
            raise RuntimeError(f'Synthesis failed: {source.name}; see {work}/synth.log')
    if not results:
        raise RuntimeError('No cached blocks found')


if __name__ == '__main__':
    main()
